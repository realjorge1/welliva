/**
 * withHealthConnect — welliva's Android Health Connect setup (prompt 04, item B).
 *
 * Used INSTEAD of react-native-health-connect's own plugin, for one reason:
 * that plugin sends Health Connect's "privacy policy" link (the permission
 * rationale) to the app's main screen, which shows Home, not a policy. Google
 * requires that link to show THE SAME privacy policy as the one declared in
 * Play Console, so here it opens welliva's privacy policy inside the app
 * (/legal/privacy — the text the website publishes from constants/legal.ts),
 * one tap from the Trust screen.
 *
 * What it adds to the Android manifest, and nothing more:
 *   1. The THREE read-only permissions welliva asks for (health-os/signals/
 *      wearable/providers/healthConnect.ts HEALTH_CONNECT_READ_TYPES): sleep,
 *      heart-rate variability, resting heart rate — what the recovery score
 *      uses. Steps and active calories were dropped (owner, 2026-11-15):
 *      nothing used them. No write permission, ever.
 *   2. HealthPermissionsRationaleActivity — answers
 *      androidx.health.ACTION_SHOW_PERMISSIONS_RATIONALE (Android 13 and
 *      earlier) and, through the ViewPermissionUsageActivity alias, the
 *      Android 14+ permission-usage intent. It opens welliva://legal/privacy and closes.
 *   3. A <queries> entry so the app can see whether Health Connect is installed.
 *
 * And it writes that one small Kotlin activity into the generated project.
 * Health Connect needs Android 8.0+ (minSdk 26): set by expo-build-properties
 * in app.json (owner approved, 2026-11-15).
 */
const fs = require("fs");
const path = require("path");
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require("@expo/config-plugins");

const READ_PERMISSIONS = [
  "android.permission.health.READ_SLEEP",
  "android.permission.health.READ_HEART_RATE_VARIABILITY",
  "android.permission.health.READ_RESTING_HEART_RATE",
];

const RATIONALE_ACTION = "androidx.health.ACTION_SHOW_PERMISSIONS_RATIONALE";
const ACTIVITY = "HealthPermissionsRationaleActivity";
const ALIAS = "ViewPermissionUsageActivity";
const HEALTH_CONNECT_PACKAGE = "com.google.android.apps.healthdata";
/** The privacy policy screen, through the app's own scheme (app.json "scheme"). */
const PRIVACY_POLICY_LINK = "welliva://legal/privacy";

function withManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults;
    AndroidConfig.Permissions.ensurePermissions(manifest, READ_PERMISSIONS);

    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);

    app.activity = app.activity || [];
    if (!app.activity.some((a) => a.$["android:name"] === `.${ACTIVITY}`)) {
      app.activity.push({
        $: {
          "android:name": `.${ACTIVITY}`,
          "android:exported": "true",
          "android:excludeFromRecents": "true",
          "android:theme": "@android:style/Theme.Translucent.NoTitleBar",
        },
        "intent-filter": [{ action: [{ $: { "android:name": RATIONALE_ACTION } }] }],
      });
    }

    app["activity-alias"] = app["activity-alias"] || [];
    if (!app["activity-alias"].some((a) => a.$["android:name"] === ALIAS)) {
      app["activity-alias"].push({
        $: {
          "android:name": ALIAS,
          "android:exported": "true",
          "android:targetActivity": `.${ACTIVITY}`,
          "android:permission": "android.permission.START_VIEW_PERMISSION_USAGE",
        },
        "intent-filter": [
          {
            action: [{ $: { "android:name": "android.intent.action.VIEW_PERMISSION_USAGE" } }],
            category: [{ $: { "android:name": "android.intent.category.HEALTH_PERMISSIONS" } }],
          },
        ],
      });
    }

    manifest.manifest.queries = manifest.manifest.queries || [];
    const queries = manifest.manifest.queries;
    const listed = queries.some((q) =>
      (q.package || []).some((p) => p.$ && p.$["android:name"] === HEALTH_CONNECT_PACKAGE),
    );
    if (!listed) queries.push({ package: [{ $: { "android:name": HEALTH_CONNECT_PACKAGE } }] });
    return cfg;
  });
}

function kotlinSource(pkg) {
  return `package ${pkg}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle

/**
 * Health Connect opens this when someone taps welliva's privacy link on its
 * permission screen (and, on Android 14+, from the permission-usage page). It
 * opens welliva's privacy policy — the same one declared in Play Console — and
 * closes. Generated by plugins/withHealthConnect.js — edit it there.
 */
class ${ACTIVITY} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    val open = Intent(Intent.ACTION_VIEW, Uri.parse("${PRIVACY_POLICY_LINK}"))
      .setPackage(packageName)
      .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    try {
      startActivity(open)
    } catch (_: Exception) {
      // No handler: nothing to show; closing is the honest fallback.
    }
    finish()
  }
}
`;
}

function withActivitySource(config) {
  return withDangerousMod(config, [
    "android",
    async (cfg) => {
      const pkg = cfg.android && cfg.android.package;
      if (!pkg) throw new Error("withHealthConnect: expo.android.package is required");
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "java", ...pkg.split("."));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${ACTIVITY}.kt`), kotlinSource(pkg));
      return cfg;
    },
  ]);
}

module.exports = function withHealthConnect(config) {
  return withActivitySource(withManifest(config));
};
// For the test that keeps the manifest and the provider's read list equal.
module.exports.READ_PERMISSIONS = READ_PERMISSIONS;
