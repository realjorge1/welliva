// Helper functions
export const getDietById = (id: string): DietData | undefined => {
  return DIET_DATABASE.find((diet) => diet.id === id);
};

export const getDietsByDifficulty = (
  difficulty: "Easy" | "Moderate" | "Advanced"
): DietData[] => {
  return DIET_DATABASE.filter((diet) => diet.difficulty === difficulty);
};

export const getSafeForCondition = (condition: string): DietData[] => {
  return DIET_DATABASE.filter((diet) =>
    diet.clinicalInfo.safeFor.some((safe) =>
      safe.toLowerCase().includes(condition.toLowerCase())
    )
  );
};

export const getNigerianMeals = (diet: DietData) => {
  return {
    breakfast: diet.breakfastOptions.filter((meal) => meal.isNigerian),
    lunch: diet.lunchOptions.filter((meal) => meal.isNigerian),
    dinner: diet.dinnerOptions.filter((meal) => meal.isNigerian),
    snacks: diet.snackOptions.filter((snack) => snack.isNigerian),
  };
};

export const getRandomMealPlan = (diet: DietData) => {
  const randomItem = <T>(arr: T[]): T =>
    arr[Math.floor(Math.random() * arr.length)];

  return {
    breakfast: randomItem(diet.breakfastOptions),
    lunch: randomItem(diet.lunchOptions),
    dinner: randomItem(diet.dinnerOptions),
    snack: randomItem(diet.snackOptions),
  };
};

export const calculateDailyTotals = (mealPlan: {
  breakfast: DietMealOption;
  lunch: DietMealOption;
  dinner: DietMealOption;
  snack: DietSnackOption;
}) => {
  const avgCalories = (range: { min: number; max: number }) =>
    Math.round((range.min + range.max) / 2);
  const avgMacro = (range: { min: number; max: number }) =>
    Math.round((range.min + range.max) / 2);

  return {
    calories:
      avgCalories(mealPlan.breakfast.calories) +
      avgCalories(mealPlan.lunch.calories) +
      avgCalories(mealPlan.dinner.calories) +
      avgCalories(mealPlan.snack.calories),
    protein:
      avgMacro(mealPlan.breakfast.protein) +
      avgMacro(mealPlan.lunch.protein) +
      avgMacro(mealPlan.dinner.protein),
    carbs:
      avgMacro(mealPlan.breakfast.carbs) +
      avgMacro(mealPlan.lunch.carbs) +
      avgMacro(mealPlan.dinner.carbs),
    fat:
      avgMacro(mealPlan.breakfast.fat) +
      avgMacro(mealPlan.lunch.fat) +
      avgMacro(mealPlan.dinner.fat),
  };
};

// Merge the curated cross-cuisine library (European/Mediterranean/Western meals
// + macro-complete snacks) into the base diets. Runs once at module load;
// name-deduped and idempotent, so re-running after the generated library is
// appended (see ensureDietLibraryLoaded) only augments the newly-added diets.
augmentDietsWithLibrary(DIET_DATABASE);

/**
 * Append the generated clinical diet library — REMOTELY (Phase D.4).
 *
 * The generated clinical library (~1 MB) used to be bundled in the app binary.
 * It's now fetched from Supabase Storage and cached on device, so it ships in
 * neither the native binary nor the initial web bundle. The hand-authored base
 * diets ({@link DIET_DATABASE}) stay bundled and ARE the offline seed: on an
 * offline first launch the loader returns nothing extra and the user still gets
 * the full base library.
 *
 * The base diets win on id collision — only genuinely new generated diets are
 * added. This loader fills the rest IN PLACE and re-augments so the generated
 * diets also receive the cross-cuisine library. It's idempotent + memoized, so
 * awaiting it repeatedly is cheap. Callers that need the full clinical library
 * (plan generation, the diet screen) should `await ensureDietLibraryLoaded()`.
 */
let _libraryLoading: Promise<DietData[]> | null = null;
export function ensureDietLibraryLoaded(): Promise<DietData[]> {
  return (_libraryLoading ??= (async () => {
    const { items } = await loadCatalog<DietData>("diet_library", "diet_library.json", []);
    for (const generated of items) {
      if (!DIET_DATABASE.some((d) => d.id === generated.id)) {
        DIET_DATABASE.push(generated);
      }
    }
    augmentDietsWithLibrary(DIET_DATABASE);
    return DIET_DATABASE;
  })());
}

