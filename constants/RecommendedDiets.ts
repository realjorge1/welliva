export const getDietById = (id: string): RecommendedDiet | undefined => {
  return RECOMMENDED_DIETS.find((diet) => diet.id === id);
};

export const getDietsByDifficulty = (
  difficulty: "Easy" | "Moderate" | "Advanced"
): RecommendedDiet[] => {
  return RECOMMENDED_DIETS.filter((diet) => diet.difficulty === difficulty);
};

export const getDietsByGoal = (goal: string): RecommendedDiet[] => {
  return RECOMMENDED_DIETS.filter((diet) =>
    diet.suitableFor.some((suitable) =>
      suitable.toLowerCase().includes(goal.toLowerCase())
    )
  );
};
